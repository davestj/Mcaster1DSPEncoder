function togglePresetsPanel() {
    var panel = document.getElementById('mixer-presets-panel');
    if (panel.style.display === 'none') {
        panel.style.display = 'block';
        loadMixerPresets();
    } else {
        panel.style.display = 'none';
    }
}

function mxEsc(s) {
    return String(s||'').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
}

function loadMixerPresets() {
    mc1Api('GET', '/api/v1/mixer/presets').then(function(d) {
        if (!d || !d.ok) return;
        var list = document.getElementById('mixer-presets-list');
        var presets = d.presets || [];
        if (presets.length === 0) {
            list.innerHTML = '<div style="color:var(--muted);font-size:.8rem;text-align:center;padding:10px">No saved presets yet</div>';
            return;
        }
        var html = '';
        presets.forEach(function(p) {
            html += '<div style="display:flex;align-items:center;justify-content:space-between;padding:8px 10px;background:rgba(255,255,255,.03);border:1px solid var(--border);border-radius:4px;margin-bottom:6px">'
                + '<div>'
                + '  <div style="font-size:.85rem;font-weight:600;color:var(--text)">' + mxEsc(p.config_name) + '</div>'
                + '  <div style="font-size:.65rem;color:var(--muted)">Vol: ' + Math.round(p.master_volume * 100) + '%</div>'
                + '</div>'
                + '<div style="display:flex;gap:4px">'
                + '  <button class="btn btn-xs btn-primary" onclick="loadMixerPreset(' + p.id + ')"><i class="fa-solid fa-download"></i> Load</button>'
                + '  <button class="btn btn-xs btn-danger" onclick="deleteMixerPreset(' + p.id + ')"><i class="fa-solid fa-trash"></i></button>'
                + '</div>'
                + '</div>';
        });
        list.innerHTML = html;
    }).catch(function() {
        document.getElementById('mixer-presets-list').innerHTML = '<div style="color:var(--red);font-size:.8rem;text-align:center;padding:10px">API unreachable</div>';
    });
}

function loadMixerPreset(id) {
    mc1Api('GET', '/api/v1/mixer/presets/' + id).then(function(d) {
        if (!d || !d.ok) { mc1Toast('Load failed', 'err'); return; }
        // Apply to mixer
        if (!window._mixer) return;
        if (d.config_name) {
            window._mixer.configName = d.config_name;
            window._mixer.configId = d.config_id;
            var nameInput = document.getElementById('mixer-config-name');
            if (nameInput) nameInput.value = d.config_name;
        }
        if (d.master_volume !== undefined) {
            window._mixer.master.volume = d.master_volume;
            window._mixer._updateFaderVisual('master', d.master_volume);
            window._mixer._sendVolume('master', d.master_volume);
        }
        if (d.channel_json && Array.isArray(d.channel_json)) {
            d.channel_json.forEach(function(saved) {
                var sid = saved.slot_id;
                if (window._mixer.channels[sid]) {
                    if (saved.volume !== undefined) {
                        window._mixer.channels[sid].volume = saved.volume;
                        window._mixer._updateFaderVisual(sid, saved.volume);
                        window._mixer._sendVolume(sid, saved.volume);
                    }
                    if (saved.pan !== undefined) {
                        window._mixer.channels[sid].pan = saved.pan;
                        window._mixer._updatePanVisual(sid, saved.pan);
                    }
                    if (saved.muted !== undefined) window._mixer.channels[sid].muted = saved.muted;
                    if (saved.solo !== undefined) window._mixer.channels[sid].solo = saved.solo;
                }
            });
        }
        mc1Toast('Preset loaded: ' + d.config_name, 'ok');
        window._mixer._render();
        togglePresetsPanel();
    }).catch(function() { mc1Toast('API unreachable', 'err'); });
}

function deleteMixerPreset(id) {
    if (!confirm('Delete this preset?')) return;
    mc1Api('DELETE', '/api/v1/mixer/presets/' + id).then(function(d) {
        if (d && d.ok) {
            mc1Toast('Preset deleted', 'ok');
            loadMixerPresets();
        } else {
            mc1Toast('Delete failed', 'err');
        }
    }).catch(function() { mc1Toast('API unreachable', 'err'); });
}

function saveAsPreset() {
    var name = prompt('Preset name:');
    if (!name || !name.trim()) return;
    name = name.trim();

    if (!window._mixer) return;
    var channelArr = [];
    for (var sid in window._mixer.channels) {
        var ch = window._mixer.channels[sid];
        channelArr.push({
            slot_id: parseInt(sid),
            volume: ch.volume,
            pan: ch.pan || 0,
            muted: !!ch.muted,
            solo: !!ch.solo
        });
    }

    mc1Api('POST', '/api/v1/mixer/presets', {
        config_name: name,
        master_volume: window._mixer.master.volume,
        channel_json: channelArr
    }).then(function(d) {
        if (d && d.ok) {
            mc1Toast('Preset saved: ' + name, 'ok');
            loadMixerPresets();
        } else {
            mc1Toast('Save failed', 'err');
        }
    }).catch(function() { mc1Toast('API unreachable', 'err'); });
}
