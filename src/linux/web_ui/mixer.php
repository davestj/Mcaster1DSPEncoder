(function() {
  document.addEventListener('DOMContentLoaded', function() {
    window._mixer = new MixerConsole();
    window._mixer.init('mixer-ch-wrap');

    // Update channel count badge and API status on poll
    var origPoll = window._mixer._poll.bind(window._mixer);
    var wrappedPoll = function() {
      origPoll();
      // After poll, update badges
      setTimeout(function() {
        var count = Object.keys(window._mixer.channels).length;
        var badge = document.getElementById('mixer-ch-count');
        if (badge) badge.textContent = count + ' Channel' + (count !== 1 ? 's' : '');

        var apiEl = document.getElementById('mixer-api-status');
        if (apiEl) {
          var hasLive = false;
          for (var sid in window._mixer.channels) {
            if (window._mixer.channels[sid].state === 'live') { hasLive = true; break; }
          }
          if (count > 0) {
            apiEl.textContent = hasLive ? 'API: Online (Live)' : 'API: Online';
            apiEl.className = 'badge ' + (hasLive ? 'badge-green' : 'badge-teal');
          }
        }
      }, 500);
    };
    window._mixer._poll = wrappedPoll;

    // Close presets panel on outside click
    document.addEventListener('click', function(e) {
      var panel = document.getElementById('mixer-presets-panel');
      var btn   = document.getElementById('btn-presets-toggle');
      if (panel && panel.style.display !== 'none' && !panel.contains(e.target) && !btn.contains(e.target)) {
        panel.style.display = 'none';
      }
    });
  });
})();

